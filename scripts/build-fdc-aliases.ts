/**
 * ADR-125 builder: resolve scripts/fdc-alias-seed.json against the live USDA FDC API,
 * extract per-100g nutrients and unit weights from USDA's OWN foodPortions, and append
 * an idempotent data section to the generated 0009 migration (marker-delimited, safe
 * to re-run). Nothing here invents a number: a target that cannot be resolved makes
 * the build FAIL, listing what did not match, so the seed can be corrected honestly.
 *
 *   npx tsx scripts/build-fdc-aliases.ts            # resolve + write pins + rewrite SQL data
 *   npx tsx scripts/build-fdc-aliases.ts --dry      # resolve + report only
 */
import dotenv from "dotenv";
import * as fs from "node:fs";
dotenv.config({ path: path.resolve(__dirname, "..", ".env.local") });
dotenv.config();
import * as path from "node:path";
import { NUTRIENT_IDS } from "../src/lib/nutrition/fdc.js";

const ROOT = path.resolve(__dirname, "..");
const SEED = path.join(ROOT, "scripts/fdc-alias-seed.json");
const PINS = path.join(ROOT, "scripts/fdc-alias-pins.json");
const MIG = path.join(ROOT, "drizzle/migrations/0009_common_martin_li.sql");
const BEGIN = "-- BEGIN fdc_alias data (generated by scripts/build-fdc-aliases.ts; do not edit by hand)";
const END = "-- END fdc_alias data";
const KEY = process.env.FDC_API_KEY ?? "";
if (!KEY) {
  console.error("FDC_API_KEY missing — this builder refuses to guess records offline.");
  process.exit(1);
}
const dry = process.argv.includes("--dry");
const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9% ]/g, " ").replace(/\s+/g, " ").trim();

type Food = { fdcId: number; description: string; dataType: string; foodNutrients?: { nutrientNumber?: string; value?: number }[] };
type Portion = { amount?: number; quantity?: string | number; modifier?: string; gramWeight?: number };

/** FDC renumbered its nutrients when Foundation switched to SR28 ids. Both are honored. */
// (NUTRIENT_IDS is imported from src/lib/nutrition/fdc.ts — one map for build time and runtime.)

async function search(query: string, dataType: string): Promise<Food[]> {
  const url = `https://api.nal.usda.gov/fdc/v1/foods/search?query=${encodeURIComponent(query)}&pageSize=10&dataType=${encodeURIComponent(dataType)}`;
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(url, { headers: { "X-Api-Key": KEY } });
    if (!r.ok) {
      if (r.status >= 500 && attempt <= 2) { await new Promise((x) => setTimeout(x, 1500)); continue; }
      throw new Error(`search ${query} -> http ${r.status}`);
    }
    return ((await r.json()) as { foods?: Food[] }).foods ?? [];
  }
}
async function full(fdcId: number): Promise<{ foodPortions?: Portion[] } | null> {
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(`https://api.nal.usda.gov/fdc/v1/food/${fdcId}?format=full`, { headers: { "X-Api-Key": KEY } });
    if (!r.ok) {
      if (r.status >= 500 && attempt <= 2) { await new Promise((x) => setTimeout(x, 1500)); continue; }
      return null;
    }
    return (await r.json()) as { foodPortions?: Portion[] };
  }
}

const UNIT_RULES: [RegExp, string][] = [
  [/tablespoon|\btbsp\b/, "tbsp"],
  [/teaspoon|\btsp\b/, "tsp"],
  [/\bcup\b/, "cup"],
  [/clove/, "clove"],
  [/slice/, "slice"],
  [/stick/, "stick"],
  [/\bcan\b/, "can"],
  [/pinch/, "pinch"],
  [/piece|each|medium|large|small|whole/, "piece"],
];
function canonUnit(modifier: string): string | null {
  for (const [re, u] of UNIT_RULES) if (re.test(modifier.toLowerCase())) return u;
  return null;
}
function qtyOf(p: Portion): number {
  if (typeof p.amount === "number" && p.amount > 0) return p.amount;
  const q = String(p.quantity ?? "1").trim();
  const m = /^(\d+)?\s*(\d+)?\s*\/\s*(\d+)?$/.exec(q);
  if (m) {
    const whole = m[1] ? Number(m[1]) : 0;
    const frac = m[2] && m[3] ? Number(m[2]) / Number(m[3]) : 0;
    const plain = !m[2] && m[1] ? Number(m[1]) : 0;
    if (whole + frac + plain > 0) return whole + frac + plain;
  }
  return 1;
}

async function main() {
const seed = JSON.parse(fs.readFileSync(SEED, "utf8")) as {
  targets: { keys: string[]; query: string; expect: string; dataType?: string }[];
};

// global key uniqueness — a key may map to exactly one record
const owner = new Map<string, string>();
for (const t of seed.targets) for (const k of t.keys) {
  const nk = norm(k);
  const seen = owner.get(nk);
  if (seen && seen !== t.query) throw new Error(`duplicate alias key "${nk}" in two targets (${seen} / ${t.query})`);
  owner.set(nk, t.query);
}

const pins: Record<string, unknown> = {};
const failures: string[] = [];
let fetched = 0;
for (const t of seed.targets) {
  const want = t.expect.split("|").map(norm);
  let resolved: Food | null = null;
  let hits: Food[] = [];
  try {
    hits = await search(t.query, t.dataType ?? "Foundation,SR Legacy,Branded");
    fetched++;
    for (const f of hits) {
      const d = norm(f.description ?? "");
      if (want.every((w) => d.includes(w))) { resolved = f; break; }
    }
  } catch (e) { failures.push(`${t.query}: ${String((e as Error).message)}`); continue; }
  if (!resolved) { failures.push(`${t.query} [expect: ${t.expect}] : no FDC record matched in top 10`); continue; }

  const food = hits.find((f) => f.fdcId === resolved!.fdcId) ?? resolved;
  const per100g: Record<string, number> = {};
  for (const [name, ids] of Object.entries(NUTRIENT_IDS)) {
    for (const num of ids) {
      const n = food.foodNutrients?.find((x) => x.nutrientNumber === num);
      if (n && typeof n.value === "number") { per100g[name] = Math.round(n.value * 1000) / 1000; break; }
    }
  }
  if (Object.keys(per100g).length === 0) { failures.push(`${t.query}: record ${food.fdcId} carries no macro nutrients — refusing`); continue; }
  if (per100g.energyKcal === undefined) console.log(`warn ${t.query}: #${food.fdcId} has no energy value (water/tea class) — alias ships macros only`);

  const unitGrams: Record<string, number> = {};
  const det = await full(food.fdcId);
  fetched++;
  for (const p of det?.foodPortions ?? []) {
    const u = p.modifier ? canonUnit(p.modifier) : null;
    if (!u || typeof p.gramWeight !== "number" || p.gramWeight <= 0) continue;
    const g = Math.round((p.gramWeight / qtyOf(p)) * 10) / 10;
    if (g > 0 && g < 2500 && unitGrams[u] === undefined) unitGrams[u] = g;
  }

  const note = `USDA FDC #${food.fdcId} "${(food.description ?? "").slice(0, 90)}" (${food.dataType}); nutrients + foodPortions fetched live by scripts/build-fdc-aliases.ts on ${new Date().toISOString().slice(0, 10)}`;
  for (const k of t.keys) pins[norm(k)] = { fdcId: String(food.fdcId), description: food.description, dataType: food.dataType, per100g, unitGrams, sourceNote: note };
  console.log(`ok  ${food.dataType.padEnd(10)} ${food.fdcId}  ${(food.description ?? "").slice(0, 60)}  units: ${Object.keys(unitGrams).join(",") || "(alias-only)"}`);
  await new Promise((r) => setTimeout(r, 120)); // stay well under 1000/hr
}

const noUnits = Object.values(pins).filter((p) => Object.keys((p as { unitGrams: object }).unitGrams).length === 0).length;
console.log(`\nresolved ${Object.keys(pins).length} keys over ${seed.targets.length - failures.length}/${seed.targets.length} targets; ${fetched} API calls; ${noUnits} records carry no USDA portion (alias-only, honest)`);
if (failures.length) {
  console.log(`\nFAILED ${failures.length}:`);
  for (const f of failures) console.log("  - " + f);
}
fs.writeFileSync(PINS, JSON.stringify(pins, null, 1));

if (!dry) {
  const esc = (s: string) => s.replace(/'/g, "''");
  const rows = Object.entries(pins).map(([k, v]) => {
    const p = v as { fdcId: string; description: string; dataType: string; per100g: object; unitGrams: object; sourceNote: string };
    return `INSERT INTO "fdc_alias" ("food_key","fdc_id","description","data_type","per_100g","unit_grams","source_note","reviewed","created_at") VALUES ('${esc(k)}', '${esc(p.fdcId)}', '${esc(p.description)}', '${esc(p.dataType)}', '${JSON.stringify(p.per100g)}'::jsonb, '${JSON.stringify(p.unitGrams)}'::jsonb, '${esc(p.sourceNote)}', false, now()) ON CONFLICT ("food_key") DO NOTHING;`;
  });
  let sql = fs.readFileSync(MIG, "utf8");
  const b = sql.indexOf(BEGIN);
  if (b >= 0) sql = sql.slice(0, b);
  sql += `\r\n${BEGIN}\r\n-- Curated name -> pinned USDA record (ADR-125). Generated from scripts/fdc-alias-pins.json;\r\n-- values are USDA's own, never typed in. reviewed=false until the dietitian pass.\r\n` + rows.join("\r\n") + `\r\n${END}\r\n`;
  fs.writeFileSync(MIG, sql);
  console.log(`\nmigration data written: ${MIG} (${rows.length} rows)`);
}
if (failures.length) process.exitCode = 1;
}
main().catch((e) => { console.error(e); process.exit(1); });
